    private static void bigO(List<LessonBlock> uk) {
        uk.add(LessonBlock.heading(MARKER));

        uk.add(LessonBlock.paragraph(
                "Уявіть, що ви написали застосунок зі списком контактів і метод пошуку "
                + "за іменем. Поки ви тестували його на десяти контактах, усе працювало "
                + "миттєво. Ви віддали застосунок людині, у якої в телефоні 50 000 контактів "
                + "— і пошук почав відчутно підвисати. Код не змінився. Телефон не зламався. "
                + "Змінилася лише кількість даних. Big-O — це інструмент, який дозволяє "
                + "передбачити таку проблему ще до того, як ви її побачите."));

        uk.add(LessonBlock.heading("Чому ми рахуємо операції, а не секунди"));
        uk.add(LessonBlock.paragraph(
                "Перша спокуса — просто заміряти час. Але секунди залежать від того, наскільки "
                + "потужний телефон, чи не крутиться поруч інший застосунок, чи встиг JIT-"
                + "компілятор оптимізувати цей метод. Один і той самий код на флагмані й на "
                + "бюджетному пристрої дасть різні числа. Тому в аналізі алгоритмів заміряють "
                + "не час, а КІЛЬКІСТЬ ОПЕРАЦІЙ — вона однакова на будь-якому залізі."));
        uk.add(LessonBlock.paragraph(
                "Ось наш наївний пошук. Прочитайте його і спробуйте самі порахувати, скільки "
                + "разів виконається тіло циклу, якщо потрібного контакту в списку немає:"));
        uk.add(LessonBlock.code(
                "String findPhone(List<Contact> contacts, String name) {\n"
                + "    for (int i = 0; i < contacts.size(); i++) {\n"
                + "        Contact c = contacts.get(i);\n"
                + "        if (c.getName().equals(name)) {\n"
                + "            return c.getPhone();\n"
                + "        }\n"
                + "    }\n"
                + "    return null;\n"
                + "}"));
        uk.add(LessonBlock.paragraph(
                "Якщо контакту немає, цикл не має шансу вийти раніше — він пройде ВЕСЬ список. "
                + "Тобто для списку з N контактів тіло циклу виконається рівно N разів. "
                + "Кожне виконання — це кілька дрібних дій: порівняти i зі списком, взяти "
                + "елемент, порівняти рядки. Скажімо, умовних 3 операції. Разом виходить "
                + "приблизно 3·N + 1 (та одиничка — це фінальний return null)."));

        uk.add(LessonBlock.heading("Чому ми викидаємо трійку й одиничку"));
        uk.add(LessonBlock.paragraph(
                "Формула 3·N + 1 виглядає точнішою за просто N — то чому ж усі кажуть, що цей "
                + "пошук має складність O(N), ігноруючи коефіцієнти? Тому що нас цікавить не "
                + "точне число операцій, а ХАРАКТЕР ЗРОСТАННЯ. Порівняйте два алгоритми на "
                + "зростаючих обсягах даних:"));
        uk.add(LessonBlock.table(
                "N (кількість контактів)\t3·N + 1 (наш пошук)\tN² (гірший алгоритм)",
                Arrays.asList(
                        "10\t31\t100",
                        "100\t301\t10 000",
                        "1 000\t3 001\t1 000 000",
                        "50 000\t150 001\t2 500 000 000")));
        uk.add(LessonBlock.paragraph(
                "На десяти елементах \"гірший\" алгоритм програє лише втричі — різниця "
                + "непомітна. Але на 50 000 елементів перший робить 150 тисяч операцій, а "
                + "другий — два з половиною мільярди. Це різниця між \"миттєво\" і \"застосунок "
                + "завис\". Саме тому коефіцієнт 3 не має значення: він додає сталий множник, "
                + "тоді як перехід від N до N² змінює саму природу зростання. Big-O навмисно "
                + "відкидає сталі й молодші доданки, щоб показати головне."));
        uk.add(LessonBlock.note(
                "Практичний наслідок: O(N) з великою сталою може бути ПОВІЛЬНІШИМ за O(N²) на "
                + "маленьких даних. Тому бібліотечні сортування (як TimSort у Java) перемикаються "
                + "на простий insertion sort для масивів менше 32-64 елементів — там O(N²) з "
                + "крихітною сталою реально швидший за O(N log N) з накладними витратами "
                + "рекурсії."));

        uk.add(LessonBlock.heading("Як читати складність прямо з коду"));
        uk.add(LessonBlock.paragraph(
                "Тепер навчимося визначати складність, дивлячись на структуру коду. Правило "
                + "перше: один цикл по N елементах дає O(N)."));
        uk.add(LessonBlock.code(
                "// O(N) — цикл виконується N разів\n"
                + "int sum = 0;\n"
                + "for (int i = 0; i < n; i++) {\n"
                + "    sum += i;\n"
                + "}"));
        uk.add(LessonBlock.paragraph(
                "Правило друге: два цикли ОДИН ЗА ОДНИМ (не вкладені) дають N + N = 2·N, "
                + "тобто все одно O(N). Сталу двійку ми, як уже знаємо, відкидаємо."));
        uk.add(LessonBlock.code(
                "// Теж O(N) — не O(N²)! Цикли послідовні, а не вкладені\n"
                + "for (int i = 0; i < n; i++) { doSomething(i); }\n"
                + "for (int j = 0; j < n; j++) { doSomethingElse(j); }"));
        uk.add(LessonBlock.paragraph(
                "Правило третє: ВКЛАДЕНІ цикли перемножуються. Зовнішній виконується N разів, "
                + "і на кожній його ітерації внутрішній виконується ще N разів — разом N·N."));
        uk.add(LessonBlock.code(
                "// O(N²) — для n = 1000 це вже мільйон ітерацій\n"
                + "for (int i = 0; i < n; i++) {\n"
                + "    for (int j = 0; j < n; j++) {\n"
                + "        if (arr[i] == arr[j] && i != j) {\n"
                + "            System.out.println(\"Знайдено дублікат: \" + arr[i]);\n"
                + "        }\n"
                + "    }\n"
                + "}"));
        uk.add(LessonBlock.paragraph(
                "Правило четверте — найважливіше й найменш очевидне: якщо на кожному кроці "
                + "задача зменшується ВДВІЧІ, складність логарифмічна, O(log N). Подивіться на "
                + "цей цикл і простежте значення n вручну:"));
        uk.add(LessonBlock.code(
                "int steps = 0;\n"
                + "while (n > 1) {\n"
                + "    n = n / 2;\n"
                + "    steps++;\n"
                + "}\n"
                + "// n = 1000 -> 500 -> 250 -> 125 -> 62 -> 31 -> 15 -> 7 -> 3 -> 1\n"
                + "// Це лише 9 кроків, щоб \"пройти\" тисячу елементів."));
        uk.add(LessonBlock.paragraph(
                "Дев'ять кроків замість тисячі. І що більший обсяг, то разючіша різниця: "
                + "для мільйона елементів знадобиться лише 20 кроків, для мільярда — 30. "
                + "Логарифм росте настільки повільно, що O(log N) на практиці майже так само "
                + "добре, як O(1). Саме тому бінарний пошук (наступний урок) настільки цінний."));

        uk.add(LessonBlock.heading("Найгірший, найкращий і середній випадок"));
        uk.add(LessonBlock.paragraph(
                "Поверніться до нашого findPhone. Ми рахували випадок, коли контакту НЕМАЄ — "
                + "цикл проходить усі N елементів. Але якщо потрібний контакт виявиться першим "
                + "у списку, метод завершиться після однієї ітерації. Виходить, у одного й "
                + "того ж коду складність різна залежно від даних:"));
        uk.add(LessonBlock.list(
                "Найкращий випадок (best case): контакт перший у списку — 1 ітерація, O(1).",
                "Середній випадок (average case): контакт десь посередині — приблизно N/2 "
                + "ітерацій, що після відкидання сталої дає O(N).",
                "Найгірший випадок (worst case): контакту немає або він останній — N ітерацій, O(N)."));
        uk.add(LessonBlock.paragraph(
                "Коли говорять \"складність цього алгоритму\", майже завжди мають на увазі "
                + "НАЙГІРШИЙ випадок. Причина проста: він дає гарантію. Якщо ви знаєте, що "
                + "гірше за O(N) не буде, ви можете спланувати поведінку застосунку. "
                + "Найкращий випадок нічого не гарантує — розраховувати на нього все одно, що "
                + "проєктувати міст, припускаючи, що по ньому ніколи не поїде вантажівка."));
        uk.add(LessonBlock.paragraph(
                "Класичний приклад, де ця різниця критична — QuickSort. У середньому він "
                + "O(N log N) і на практиці дуже швидкий, але на невдалих даних деградує до "
                + "O(N²). Ми детально розберемо, чому саме так, у наступному уроці про сортування."));

        uk.add(LessonBlock.heading("Три позначення: O, Ω та Θ"));
        uk.add(LessonBlock.paragraph(
                "Big-O — це не єдина нотація, просто найпопулярніша. Формально вона описує лише "
                + "ВЕРХНЮ межу: \"алгоритм працює не гірше, ніж…\". Є ще дві:"));
        uk.add(LessonBlock.table(
                "Позначення\tЩо означає\tЯк читати вголос",
                Arrays.asList(
                        "O(f(n))\tВерхня межа — не гірше ніж f(n)\t\"Зростає щонайбільше як f(n)\"",
                        "Ω(f(n))\tНижня межа — не краще ніж f(n)\t\"Зростає щонайменше як f(n)\"",
                        "Θ(f(n))\tТочна межа — і зверху, і знизу\t\"Зростає рівно як f(n)\"")));
        uk.add(LessonBlock.paragraph(
                "Технічно правильно сказати, що наш findPhone має складність O(N²) — адже "
                + "\"не гірше ніж N²\" це правда, N справді не гірше за N². Просто це нікому не "
                + "корисне твердження, бо надто слабке. Тому на практиці, кажучи O(N), майже "
                + "завжди мають на увазі Θ(N) — точну оцінку. Формально це неточність, але "
                + "вона настільки усталена, що ви зустрінете її і в документації, і на "
                + "співбесідах, і в цьому курсі."));

        uk.add(LessonBlock.heading("Амортизована складність: чому ArrayList.add() це O(1)"));
        uk.add(LessonBlock.paragraph(
                "Ось цікавий випадок, де \"найгірший випадок\" вводить в оману. Усередині "
                + "ArrayList — звичайний масив фіксованого розміру. Коли ви додаєте елемент, а "
                + "масив уже заповнений, ArrayList не може просто \"розширити\" його: у Java "
                + "масив не змінює розмір. Тому він створює НОВИЙ масив (приблизно у півтора "
                + "рази більший) і копіює туди все старе вміст. Це операція на O(N)."));
        uk.add(LessonBlock.paragraph(
                "Здавалося б, add() має складність O(N) у найгіршому випадку — і формально так "
                + "і є. Але подивімося, що відбувається протягом довгої серії викликів. "
                + "Припустимо, місткість подвоюється, і ми починаємо з масиву на 4 елементи:"));
        uk.add(LessonBlock.table(
                "Виклик add() №\tЩо відбувається\tСкопійовано елементів",
                Arrays.asList(
                        "1-4\tПросто запис у вільну комірку\t0",
                        "5\tМісця немає: новий масив на 8, копіювання\t4",
                        "6-8\tПросто запис\t0",
                        "9\tНовий масив на 16, копіювання\t8",
                        "10-16\tПросто запис\t0",
                        "17\tНовий масив на 32, копіювання\t16")));
        uk.add(LessonBlock.paragraph(
                "Дорогі операції трапляються, але дедалі рідше: між ними проміжок, що "
                + "подвоюється. Якщо скласти ВСЮ роботу за 17 викликів (4 + 8 + 16 = 28 "
                + "копіювань) і поділити на кількість викликів, вийде менше двох копіювань на "
                + "виклик — і це співвідношення не зростає, скільки б елементів ви не додавали. "
                + "Саме це називають АМОРТИЗОВАНОЮ складністю O(1): окремий виклик може бути "
                + "повільним, але вартість, розмазана по всій серії, лишається сталою."));
        uk.add(LessonBlock.warning(
                "Амортизована O(1) — це не те саме, що гарантована O(1). Якщо ви пишете код, "
                + "де важлива передбачуваність КОЖНОЇ окремої операції (наприклад, обробка "
                + "аудіо в реальному часі, де пропуск дедлайну чути як клацання), раптове "
                + "копіювання мільйона елементів посеред циклу — реальна проблема. У такому "
                + "разі задайте місткість наперед: new ArrayList<>(1_000_000)."));

        uk.add(LessonBlock.heading("Пам'ять теж має складність"));
        uk.add(LessonBlock.paragraph(
                "Досі ми говорили лише про час, але Big-O так само описує споживання пам'яті. "
                + "І тут часто виникає компроміс: пришвидшити алгоритм можна, витративши більше "
                + "пам'яті. Подивіться на два способи знайти дублікати в масиві."));
        uk.add(LessonBlock.code(
                "// Варіант 1: час O(N²), пам'ять O(1)\n"
                + "// Порівнюємо кожен з кожним. Нічого додатково не зберігаємо.\n"
                + "boolean hasDuplicates(int[] arr) {\n"
                + "    for (int i = 0; i < arr.length; i++) {\n"
                + "        for (int j = i + 1; j < arr.length; j++) {\n"
                + "            if (arr[i] == arr[j]) return true;\n"
                + "        }\n"
                + "    }\n"
                + "    return false;\n"
                + "}"));
        uk.add(LessonBlock.paragraph(
                "Цей варіант нічого не запам'ятовує — саме тому пам'ять O(1). Але за це він "
                + "платить часом: щоб дізнатися, чи зустрічалося число раніше, доводиться "
                + "щоразу перебирати весь масив заново. А тепер зробімо навпаки: заплатимо "
                + "пам'яттю, щоб не перебирати."));
        uk.add(LessonBlock.code(
                "// Варіант 2: час O(N), пам'ять O(N)\n"
                + "// Один прохід, але тримаємо множину побачених чисел.\n"
                + "boolean hasDuplicates(int[] arr) {\n"
                + "    Set<Integer> seen = new HashSet<Integer>();\n"
                + "    for (int value : arr) {\n"
                + "        if (!seen.add(value)) return true; // add() поверне false, якщо вже було\n"
                + "    }\n"
                + "    return false;\n"
                + "}"));
        uk.add(LessonBlock.paragraph(
                "Другий варіант радикально швидший, але за це доводиться платити: HashSet у "
                + "гіршому випадку зберігатиме всі N чисел. На мільйоні елементів це десятки "
                + "мегабайтів. На сервері таке рішення очевидне; на старому Android-пристрої з "
                + "обмеженою купою — уже не факт. Правильної відповіді \"взагалі\" немає, є "
                + "лише правильна відповідь для конкретних обмежень."));

        uk.add(LessonBlock.heading("Практичне завдання"));
        uk.add(LessonBlock.paragraph("Напишіть метод findMax(int[] arr), який знаходить максимальне значення в масиві. Яка часова складність (Big-O) вашого рішення?"));
        uk.add(LessonBlock.heading("Рішення"));
        uk.add(LessonBlock.code(
                "int findMax(int[] arr) {\n"
                + "    int max = arr[0];\n"
                + "    for (int i = 1; i < arr.length; i++) {\n"
                + "        if (arr[i] > max) {\n"
                + "            max = arr[i];\n"
                + "        }\n"
                + "    }\n"
                + "    return max;\n"
                + "}\n"
                + "// Складність: O(N), оскільки цикл проходить по всіх елементах масиву рівно один раз."));
    }

